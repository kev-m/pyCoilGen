def reference_biot_savart_calc_b(wire_elements: np.ndarray, target_f: TargetField):
    """
    Calculate the magnetic field using Biot-Savart law for wire elements given as a sequence of coordinate points.

    Args:
        wire_elements (ndarray): A sequence of coordinate points representing wire elements (m,3).
        target_f: The target field.

    Returns:
        ndarray: The magnetic field calculated using Biot-Savart law with shape (3, num_tp).
    """
    num_tp = target_f.coords.shape[1]  # (3,n)
    track_part_length = 2000

    if wire_elements.shape[1] > track_part_length:  # (3,7)
        track_part_inds = np.arange(0, wire_elements.shape[1], track_part_length)
        track_part_inds = np.append(track_part_inds, wire_elements.shape[1])

        if track_part_inds[-2] == track_part_inds[-1]:
            track_part_inds = track_part_inds[:-1]

        wire_parts = []

        part_ind_start = track_part_inds[0]
        for i in range(len(track_part_inds) - 1):
            part_ind_end = track_part_inds[i + 1]
            coord = wire_elements[:, part_ind_start:part_ind_end]
            seg_coords = (wire_elements[:, part_ind_start:(part_ind_end - 1)] +
                          wire_elements[:, (part_ind_start + 1):part_ind_end]) / 2
            currents = wire_elements[:, (part_ind_start + 1):part_ind_end] - \
                wire_elements[:, part_ind_start:(part_ind_end - 1)]
            wire_part = WirePart(seg_coords=seg_coords, currents=currents)
            wire_parts.append(wire_part)
            # Start next loop before the last point of the previous, since the last point is not used in the loop below
            part_ind_start = part_ind_end-1

    else:
        coord = wire_elements
        seg_coords = (wire_elements[:, :-1] + wire_elements[:, 1:]) / 2  # M: 3x6
        currents = wire_elements[:, 1:] - wire_elements[:, :-1]
        wire_part = WirePart(seg_coords=seg_coords, currents=currents)
        wire_parts = [wire_part]

    # Based on code generated by ChatGPT July 20 Version
    # mu0 = 4 * np.pi * 1e-7  # Permeability of free space

    # NOTE: Using Python (num_vertices, xyz) matrix layout
    b_field = np.zeros((num_tp, 3))

    # Extract target cooordinates
    target_coords_T = target_f.coords.T

    for wire_part in wire_parts:  # M: target_f.coords => 3x257, wire_part.seg_coords => 3x6
        # Extract the wire segment co-ordinates
        w_seg_coords_T = wire_part.seg_coords.T
        # Extract the wire segment currents
        w_currents_T = wire_part.currents.T  # -> 6,3

        # Calculate the vector from each target point to each conductor fragment
        r = target_coords_T[:, np.newaxis] - w_seg_coords_T

        # Calculate the distance from each target point to each conductor fragment
        r_norm = np.linalg.norm(r, axis=2)**3

        # Calculate the cross product between r and currents along the last axis
        r_cross_I = np.cross(w_currents_T, r, axis=-1)

        # Calculate the magnetic field for each target point using broadcasting
        dB = r_cross_I / (r_norm)[:, :, np.newaxis]
        # b_field_part = mu0 / (4 * np.pi) * np.sum(dB, axis=1)
        b_field_part = 1e-7 * np.sum(dB, axis=1)

        b_field += b_field_part

    # NOTE: Returning MATLAB 3xM layout
    return b_field.T


def reference_gradient_calc_3(wire_elements, target_coords):
    """
    Calculate the gradient of magnetic field using Biot-Savart law.

    Args:
        wire_elements (numpy.ndarray): Array of wire element coordinates. Shape: (m, 3).
        target_coords (numpy.ndarray): Array of target coordinates. Shape: (n, 3).

    Returns:
        numpy.ndarray: Gradient components dBxdxyz, DBydxyz, DBzdxyz. Shape: (3, n).

    """
    num_tp = target_coords.shape[0]
    track_part_length = 1000

    if wire_elements.shape[0] > track_part_length:
        track_part_inds = np.arange(0, wire_elements.shape[0], track_part_length)
        track_part_inds = np.append(track_part_inds, wire_elements.shape[0])
        if track_part_inds[-2] == track_part_inds[-1]:
            track_part_inds = track_part_inds[:-1]

        wire_parts = []
        part_ind_start = track_part_inds[0]
        for i in range(len(track_part_inds) - 1):
            part_ind_end = track_part_inds[i + 1]
            wire_part = WirePart()
            wire_part.coord = wire_elements[part_ind_start:part_ind_end, :]
            wire_part.seg_coords = (wire_part.coord[:-1, :] + wire_part.coord[1:, :]) / 2
            wire_part.currents = wire_part.coord[1:, :] - wire_part.coord[:-1, :]
            wire_parts.append(wire_part)
            # Start next loop before the last point of the previous, since the last point is not used in the loop below
            part_ind_start = part_ind_end-1
    else:
        wire_part = WirePart()
        wire_part.coord = wire_elements
        wire_part.seg_coords = (wire_part.coord[:-1, :] + wire_part.coord[1:, :]) / 2
        wire_part.currents = wire_part.coord[1:, :] - wire_part.coord[:-1, :]
        wire_parts = [wire_part]

    DBxdxyz = np.zeros((num_tp, 3))
    DBydxyz = np.zeros((num_tp, 3))
    DBzdxyz = np.zeros((num_tp, 3))
    for wire_part in wire_parts:
        target_p = np.repeat(target_coords[np.newaxis, :, :], wire_part.seg_coords.shape[0], axis=0)
        cur_pos = np.repeat(wire_part.seg_coords[:, np.newaxis, :], num_tp, axis=1)
        cur_dir = np.repeat(wire_part.currents[:, np.newaxis, :], num_tp, axis=1)

        x = target_p[:, :, 0]
        y = target_p[:, :, 1]
        z = target_p[:, :, 2]
        l_x = cur_pos[:, :, 0]
        l_y = cur_pos[:, :, 1]
        l_z = cur_pos[:, :, 2]
        d_l_x = cur_dir[:, :, 0]
        d_l_y = cur_dir[:, :, 1]
        d_l_z = cur_dir[:, :, 2]

        """
        E = ((x - l_x)**2 + (y - l_y)**2 + (z - l_z)**2)**(3/2)
        dEdx = 3 * (x - l_x) * ((x - l_x)**2 + (y - l_y)**2 + (z - l_z)**2)**(1/2)
        dEdy = 3 * (y - l_y) * ((x - l_x)**2 + (y - l_y)**2 + (z - l_z)**2)**(1/2)
        dEdz = 3 * (z - l_z) * ((x - l_x)**2 + (y - l_y)**2 + (z - l_z)**2)**(1/2)
        """
        # Optimized
        squared_difference = (x - l_x)**2. + (y - l_y)**2. + (z - l_z)**2.
        E = squared_difference**(3./2.)
        sqrt_squared_difference = np.sqrt(squared_difference)
        dEdx = 3. * (x - l_x) * sqrt_squared_difference
        dEdy = 3. * (y - l_y) * sqrt_squared_difference
        dEdz = 3. * (z - l_z) * sqrt_squared_difference

        C = 1e-7

        phi_x = d_l_y * (z - l_z) - d_l_z * (y - l_y)
        phi_y = d_l_z * (x - l_x) - d_l_x * (z - l_z)
        phi_z = d_l_x * (y - l_y) - d_l_y * (x - l_x)

        theta_factor = ((E**2)**(-1.)) * (-1.) * C

        theta_dEdx = theta_factor * dEdx
        theta_dEdy = theta_factor * dEdy
        theta_dEdz = theta_factor * dEdz
        E_inv_C = (E**(-1.)) * C

        dBx_dx = theta_dEdx * phi_x
        dBx_dy = theta_dEdy * phi_x + E_inv_C * (-1.) * d_l_z
        dBx_dz = theta_dEdz * phi_x + E_inv_C * d_l_y

        dBy_dx = theta_dEdx * phi_y + E_inv_C * d_l_z
        dBy_dy = theta_dEdy * phi_y
        dBy_dz = theta_dEdz * phi_y + E_inv_C * (-1.) * d_l_x

        dBz_dx = theta_dEdx * phi_z + E_inv_C * (-1.) * d_l_y
        dBz_dy = theta_dEdy * phi_z + E_inv_C * d_l_x
        dBz_dz = theta_dEdz * phi_z

        # Accumulate gradients
        DBxdxyz += np.column_stack((np.sum(dBx_dx, axis=0), np.sum(dBx_dy, axis=0), np.sum(dBx_dz, axis=0)))
        DBydxyz += np.column_stack((np.sum(dBy_dx, axis=0), np.sum(dBy_dy, axis=0), np.sum(dBy_dz, axis=0)))
        DBzdxyz += np.column_stack((np.sum(dBz_dx, axis=0), np.sum(dBz_dy, axis=0), np.sum(dBz_dz, axis=0)))

    return DBxdxyz, DBydxyz, DBzdxyz


def _wire_and_targets(num_points, num_targets, seed):
    rng = np.random.default_rng(seed)
    t = np.linspace(0, 6 * np.pi, num_points)
    wire = np.column_stack((0.3 * np.cos(t), 0.3 * np.sin(t), 0.02 * t / np.pi - 0.1 + 0.01 * rng.standard_normal(num_points)))
    targets = (rng.random((num_targets, 3)) - 0.5) * 0.2
    targets[0] = wire[num_points // 2] + [0.0, 0.0, 1e-3]   # Only 1 mm from the wire, far from the origin
    return wire, targets


@pytest.mark.parametrize('num_points', [2, 7, 400, 2500])   # Below and above the chunk sizes of the original
@pytest.mark.parametrize('num_targets', [1, 37, 700])       # Below and above the target block size
def test_biot_savart_field_matches_the_original(num_points, num_targets):
    wire, targets = _wire_and_targets(num_points, num_targets, 1)
    target_field = TargetField(coords=targets.T.copy())
    expected = reference_biot_savart_calc_b(wire.T.copy(), target_field)
    actual = biot_savart_calc_b(wire.T.copy(), target_field)
    assert actual.shape == expected.shape == (3, num_targets)
    np.testing.assert_allclose(actual, expected, rtol=1e-9, atol=1e-12 * np.abs(expected).max())


@pytest.mark.parametrize('num_points', [2, 7, 400, 2500])
@pytest.mark.parametrize('num_targets', [1, 37, 700])
def test_gradient_matches_the_original(num_points, num_targets):
    wire, targets = _wire_and_targets(num_points, num_targets, 2)
    expected = reference_gradient_calc_3(wire, targets)
    actual = direct_biot_savart_gradient_calc_3(wire, targets)
    for a, e in zip(actual, expected):
        assert a.shape == e.shape == (num_targets, 3)
        np.testing.assert_allclose(a, e, rtol=1e-9, atol=1e-12 * np.abs(e).max())


def test_block_size_does_not_change_the_result(monkeypatch):
    wire, targets = _wire_and_targets(300, 50, 3)
    target_field = TargetField(coords=targets.T.copy())
    expected = biot_savart_calc_b(wire.T.copy(), target_field)
    expected_gradient = direct_biot_savart_gradient_calc_3(wire, targets)
    monkeypatch.setattr(wire_kernels, '_PAIRS_PER_BLOCK', 7)
    monkeypatch.setattr(wire_kernels, '_MAX_TARGETS_PER_BLOCK', 3)
    np.testing.assert_allclose(biot_savart_calc_b(wire.T.copy(), target_field), expected, rtol=1e-12)
    for a, e in zip(direct_biot_savart_gradient_calc_3(wire, targets), expected_gradient):
        np.testing.assert_allclose(a, e, rtol=1e-10, atol=1e-12 * np.abs(e).max())
